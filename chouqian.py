# -*- coding: utf-8 -*-
# =====================================================================
# 随机点名器（Python 新手版）
# 作用：输入一串名字，程序随机抽一个并打印出来
# 说明：每一行代码后面都写了中文注释，可以对照着理解
# =====================================================================

import random  # 导入 Python 自带的 random（随机）模块，用它来做随机抽取

print("=" * 40)  # 打印 40 个等号组成的分隔线，让画面看起来整齐一点
print("      欢迎使用「随机点名器」")  # 打印欢迎语，告诉用户这个程序是做什么的
print("=" * 40)  # 再打印一条一样的分隔线，把欢迎语上下夹起来

while True:  # 开始一个"无限循环"：只要用户没输入有效名字，就不停地重新问
    text = input("请输入名字（用空格或逗号分开）：")  # 让用户输入一串名字，存进变量 text
    text = text.replace("，", ",")  # 把中文逗号换成英文逗号，防止中文输入法导致切分失败
    text = text.replace(",", " ")  # 再把英文逗号换成空格，这样后面只要按空格切分就够了
    text = text.replace("、", " ")  # 顺带把中文顿号也换成空格，照顾不同的输入习惯
    names = text.split()  # 用 split() 按空白把整串文字切成"列表"，每个元素就是一个名字

    if len(names) == 0:  # len() 用来数列表里有多少个名字，等于 0 说明用户什么都没输入
        print("你还没有输入名字，请重新输入～")  # 打印提示，让用户再输一次
        continue  # 跳过本次循环剩下的代码，直接回到 while 开头重新提问

    break  # 名字数量大于 0，说明输入有效，用 break 跳出循环，继续往下执行

winner = random.choice(names)  # 用 random.choice() 从名字列表里随机挑出一个，存到 winner
print()  # 打印一个空行，让最终结果更醒目
print("这次被点到的名字是：", winner)  # 把抽到的名字打印出来，这就是最终结果
print("（本次共有 %d 个名字参与抽取）" % len(names))  # 顺便告诉用户一共有几个名字参与了抽取

